#[test]
fn source_then_release_in_one_push_requires_full_ci() {
    let repo = Repo::new();
    let base = repo.git(&["rev-parse", "HEAD"]);
    fs::write(repo.0.join("src/lib.rs"), "pub fn changed() {}\n").unwrap();
    let source = repo.commit("source");
    repo.version("0.107.3");
    let head = repo.commit("release");
    assert!(repo.classified("push", &source, &head));
    assert!(!repo.classified("push", &base, &head));
}

#[test]
fn real_source_pr_merge_never_uses_slim_path() {
    let repo = Repo::new();
    let base = repo.git(&["rev-parse", "HEAD"]);
    repo.git(&["checkout", "-q", "-b", "feature"]);
    fs::write(repo.0.join("src/lib.rs"), "pub fn changed() {}\n").unwrap();
    repo.commit("release-looking source change");
    repo.git(&["checkout", "-q", "master"]);
    repo.git(&["merge", "-q", "--no-ff", "feature", "-m", "chore: release"]);
    let head = repo.git(&["rev-parse", "HEAD"]);
    assert!(!repo.classified("push", &base, &head));
}

#[test]
fn synthetic_pr_with_new_base_code_requires_normal_checks() {
    let repo = Repo::new();
    let base = repo.git(&["rev-parse", "HEAD"]);
    repo.git(&["checkout", "-q", "-b", "release"]);
    repo.version("0.107.3");
    let head = repo.commit("release");
    repo.git(&["checkout", "-q", "master"]);
    fs::write(repo.0.join("src/lib.rs"), "pub fn new_base() {}\n").unwrap();
    let newer_base = repo.commit("new master code");
    repo.git(&["merge", "-q", "--no-ff", "release", "-m", "synthetic merge"]);
    assert!(!repo.classified("pull_request", &base, &head));
    assert!(!repo.classified("pull_request", &newer_base, &head));
    repo.git(&["checkout", "-q", "release"]);
    assert!(repo.classified("pull_request", &newer_base, &head));
    assert!(!repo.classified("push", &newer_base, &head));
}

#[test]
fn invalid_versions_and_nonadvancing_releases_fail_closed() {
    for version in [
        "invalid",
        "0.107.2",
        "0.107.1",
        "00.107.3",
        "0.107",
        "0.107.3.1",
        "0.107.3-beta",
        "0.107.3+build",
        "0.107.-3",
        "18446744073709551616.0.0",
    ] {
        let repo = Repo::new();
        let base = repo.git(&["rev-parse", "HEAD"]);
        repo.version(version);
        let head = repo.commit(&format!("invalid {version}"));
        assert!(!repo.classified("push", &base, &head), "{version}");
    }
}

#[test]
fn only_root_manifest_and_lock_versions_may_change() {
    for (path, old, new) in [
        ("Cargo.toml", "serde = \"1\"", "serde = \"2\""),
        ("Cargo.toml", "edition = \"2024\"", "edition = \"2021\""),
        ("Cargo.toml", "name = \"decapod\"", "name = \"another\""),
        ("Cargo.lock", "version = \"1.0.0\"", "version = \"1.0.1\""),
        (
            "Cargo.lock",
            "checksum = \"unchanged\"",
            "checksum = \"changed\"",
        ),
        ("Cargo.lock", " \"serde\",", " \"another\","),
        (
            "Cargo.lock",
            "registry+https://example.invalid",
            "git+https://example.invalid",
        ),
    ] {
        let repo = Repo::new();
        let base = repo.git(&["rev-parse", "HEAD"]);
        repo.version("0.107.3");
        repo.replace(path, old, new);
        let head = repo.commit("mixed metadata");
        assert!(!repo.classified("push", &base, &head), "{path}: {new}");
    }
}

#[test]
fn missing_mismatched_or_duplicate_lock_root_fails_closed() {
    for transform in [0, 1, 2, 3] {
        let repo = Repo::new();
        let base = repo.git(&["rev-parse", "HEAD"]);
        repo.version("0.107.3");
        match transform {
            0 => repo.replace("Cargo.lock", "name = \"decapod\"", "name = \"missing\""),
            1 => repo.replace(
                "Cargo.lock",
                "version = \"0.107.3\"",
                "version = \"0.107.4\"",
            ),
            2 => repo.replace("Cargo.lock", "name = \"serde\"", "name = \"decapod\""),
            _ => repo.replace(
                "Cargo.lock",
                "version = \"0.107.3\"",
                "version = \"0.107.3\"\nsource = \"registry+https://example.invalid\"",
            ),
        }
        let head = repo.commit("bad lock");
        assert!(!repo.classified("push", &base, &head));
    }
}

