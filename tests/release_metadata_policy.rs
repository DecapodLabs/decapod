//! The release fast path is a proof about Git objects, not PR labels or titles.
#![allow(dead_code)]
#[path = "../assets/tools/release_metadata.rs"]
mod release_metadata;

use std::fs;
use std::path::PathBuf;
use std::process::Command;
use std::sync::atomic::{AtomicUsize, Ordering};

static NEXT: AtomicUsize = AtomicUsize::new(0);

struct Repo(PathBuf);
impl Drop for Repo {
    fn drop(&mut self) {
        fs::remove_dir_all(&self.0).expect("remove owned fixture");
    }
}
impl Repo {
    fn new() -> Self {
        let root = std::env::temp_dir().join(format!(
            "decapod-release-metadata-{}-{}",
            std::process::id(),
            NEXT.fetch_add(1, Ordering::Relaxed)
        ));
        fs::create_dir(&root).expect("create private fixture");
        let repo = Self(root);
        repo.git(&["init", "-q", "-b", "master"]);
        repo.git(&["config", "user.name", "Release fixture"]);
        repo.git(&["config", "user.email", "release-fixture@example.invalid"]);
        repo.version("0.107.2");
        fs::write(repo.0.join("CHANGELOG.md"), "# Changelog\n").unwrap();
        fs::create_dir(repo.0.join("src")).unwrap();
        fs::write(repo.0.join("src/lib.rs"), "pub fn original() {}\n").unwrap();
        repo.commit("base");
        repo
    }
    fn git(&self, args: &[&str]) -> String {
        let result = Command::new("git")
            .arg("-C")
            .arg(&self.0)
            .args(args)
            .output()
            .unwrap();
        assert!(
            result.status.success(),
            "git {args:?}: {}",
            String::from_utf8_lossy(&result.stderr)
        );
        String::from_utf8(result.stdout).unwrap().trim().to_string()
    }
    fn version(&self, version: &str) {
        fs::write(self.0.join("Cargo.toml"), format!(
            "[package]\nname = \"decapod\"\ndefault-run = \"decapod\"\nversion = \"{version}\"\nedition = \"2024\"\n\n[dependencies]\nserde = \"1\"\n"
        )).unwrap();
        fs::write(self.0.join("Cargo.lock"), format!(
            "# This file is automatically @generated by Cargo.\nversion = 4\n\n[[package]]\nname = \"decapod\"\nversion = \"{version}\"\ndependencies = [\n \"serde\",\n]\n\n[[package]]\nname = \"serde\"\nversion = \"1.0.0\"\nsource = \"registry+https://example.invalid\"\nchecksum = \"unchanged\"\n"
        )).unwrap();
    }
    fn commit(&self, message: &str) -> String {
        self.git(&["add", "."]);
        self.git(&["commit", "-q", "--allow-empty", "-m", message]);
        self.git(&["rev-parse", "HEAD"])
    }
    fn classified(&self, event: &str, base: &str, head: &str) -> bool {
        release_metadata::classify(&self.0, event, base, head).unwrap_or(false)
    }
    fn replace(&self, path: &str, old: &str, new: &str) {
        let path = self.0.join(path);
        let before = fs::read_to_string(&path).unwrap();
        assert!(before.contains(old));
        fs::write(path, before.replace(old, new)).unwrap();
    }
}

#[test]
fn version_only_squash_push_and_pr_are_slim() {
    let repo = Repo::new();
    let base = repo.git(&["rev-parse", "HEAD"]);
    repo.version("0.107.3");
    fs::write(
        repo.0.join("CHANGELOG.md"),
        "# Changelog\n\nRelease 0.107.3\n",
    )
    .unwrap();
    let head = repo.commit("arbitrary title; no release label required");
    assert!(repo.classified("push", &base, &head));
    assert!(repo.classified("pull_request", &base, &head));
    assert!(!repo.classified("workflow_dispatch", &base, &head));
}

#[test]
fn normal_merge_uses_pre_push_base_not_final_parent() {
    let repo = Repo::new();
    let base = repo.git(&["rev-parse", "HEAD"]);
    repo.git(&["checkout", "-q", "-b", "release"]);
    repo.version("0.107.3");
    repo.commit("release version");
    repo.git(&["checkout", "-q", "master"]);
    repo.git(&["merge", "-q", "--no-ff", "release", "-m", "merge"]);
    let head = repo.git(&["rev-parse", "HEAD"]);
    assert!(repo.classified("push", &base, &head));
}

